"""Turn the 2D character renders (front + back side by side on a light-gray
studio background) into transparent, trimmed sprites the game can draw.

Usage: python3 tools/cut_renders.py <folder of render jpgs>
  reads  art/renders/sources.json   (kid id -> render file name)
  writes art/renders/<id>-front.webp, <id>-back.webp
         src/data/renders.js        (the sprites inlined as data URIs)
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / 'art' / 'renders'
SPRITE_H = 320  # stored height of each trimmed figure


def background_model(rgb):
    """Smooth estimate of the studio backdrop: a quadratic surface fit to the image border."""
    h, w, _ = rgb.shape
    lum = rgb.mean(axis=2)
    ys, xs = np.mgrid[0:h, 0:w]
    border = np.zeros((h, w), bool)
    border[:12, :] = border[-12:, :] = True
    border[:, :12] = border[:, -12:] = True
    X, Y = xs[border] / w, ys[border] / h
    A = np.stack([np.ones_like(X), X, Y, X * X, Y * Y, X * Y], 1)
    coef, *_ = np.linalg.lstsq(A, lum[border], rcond=None)
    Xa, Ya = xs / w, ys / h
    return coef[0] + coef[1] * Xa + coef[2] * Ya + coef[3] * Xa ** 2 + coef[4] * Ya ** 2 + coef[5] * Xa * Ya


def cut(img):
    """Return an RGBA copy of img with the backdrop (and the soft floor shadows) made transparent."""
    rgb = np.asarray(img.convert('RGB')).astype(np.float32)
    h, w, _ = rgb.shape
    lum = rgb.mean(axis=2)
    sat = rgb.max(axis=2) - rgb.min(axis=2)
    bg = background_model(rgb)
    diff = lum - bg
    # backdrop-like: gray, and not brighter than the wall (white shoes/socks are brighter)
    # the backdrop is smooth; shoes, socks and clothes have edges and texture
    gy, gx = np.gradient(lum)
    smooth = np.asarray(Image.fromarray(np.hypot(gx, gy).astype(np.float32)).filter(ImageFilter.MaxFilter(5))) < 4.5
    # backdrop-like: gray, close to the wall's brightness, and smooth
    cand = (sat < 12) & (diff < 5) & (diff > -16) & smooth
    # soft contact shadows on the floor are darker, but still gray and smooth
    floor = np.zeros_like(cand)
    floor[int(h * 0.80):, :] = True
    cand |= floor & (sat < 12) & (diff < 5) & (diff > -60) & smooth
    # keep only backdrop pixels connected to the image edge
    m = Image.fromarray(np.where(cand, 255, 0).astype(np.uint8)).copy()  # (floodfill is a no-op on array-backed images)
    for x in range(0, w, 6):
        for y in (0, h - 1):
            if m.getpixel((x, y)) == 255:
                ImageDraw.floodfill(m, (x, y), 128)
    for y in range(0, h, 6):
        for x in (0, w - 1):
            if m.getpixel((x, y)) == 255:
                ImageDraw.floodfill(m, (x, y), 128)
    bgmask = np.asarray(m) == 128
    alpha = Image.fromarray(np.where(bgmask, 0, 255).astype(np.uint8))
    # drop specks, tighten and soften the edge
    alpha = alpha.filter(ImageFilter.MedianFilter(5)).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.9))
    out = img.convert('RGB').copy()
    out.putalpha(alpha)
    return out


def trim(rgba):
    a = np.asarray(rgba)[:, :, 3]
    ys, xs = np.where(a > 40)
    pad = 4
    box = (max(0, xs.min() - pad), max(0, ys.min() - pad), min(rgba.width, xs.max() + pad + 1), min(rgba.height, ys.max() + pad + 1))
    t = rgba.crop(box)
    s = SPRITE_H / t.height
    return t.resize((max(1, round(t.width * s)), SPRITE_H), Image.LANCZOS)


def main():
    src = Path(sys.argv[1])
    mapping = {k: v for k, v in json.loads((OUT_DIR / 'sources.json').read_text()).items() if not k.startswith('_')}
    entries = []
    for kid, name in sorted(mapping.items()):
        img = Image.open(src / name)
        half = img.width // 2
        views = {}
        for view, box in (('front', (0, 0, half, img.height)), ('back', (half, 0, img.width, img.height))):
            sprite = trim(cut(img.crop(box)))
            path = OUT_DIR / f'{kid}-{view}.webp'
            sprite.save(path, 'WEBP', quality=84, method=6)
            buf = io.BytesIO()
            sprite.save(buf, 'WEBP', quality=84, method=6)
            views[view] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
        entries.append((kid, views))
        print(kid, name)
    lines = [
        '// Generated by tools/cut_renders.py from art/renders/sources.json. Do not edit by hand.',
        '// Polished 2D renders (transparent, trimmed, front + back) for kids that have one.',
        'export const RENDERS = {',
    ]
    for kid, v in entries:
        lines.append(f"  '{kid}': {{ front: '{v['front']}', back: '{v['back']}' }},")
    lines.append('};')
    (ROOT / 'src' / 'data' / 'renders.js').write_text('\n'.join(lines) + '\n')
    print(f'{len(entries)} kids -> src/data/renders.js')


if __name__ == '__main__':
    main()
